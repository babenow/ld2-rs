//! OS-уведомления (D7, НФР обновления/события): 4+ события — смерть,
//! приглашения (пати/гильдия), открытие сделки, whisper, результат
//! улучшения. Флаг — `config.notify` (feature-flag `desktop.notify`).

/// Показ системного уведомления (ошибка — в лог, не фатально).
///
/// **Поток показа — платформенный:**
/// * **macOS — синхронно, из вызывающего потока.** `notify-rust` здесь
///   идёт через legacy `NSUserNotification` (Cocoa): такой API обязан
///   вызываться из **главного** потока. Фоновый вызов (как было раньше,
///   общий для всех платформ) приводил к тому, что в момент показа
///   уведомления поднимались `UserNotificationCenter` **и**
///   `CoreServicesUIAgent` — и игрок видел системный диалог
///   «выбор приложения» (будто приложение пытается открыть файл).
///   Замечено на завершении заточки: секунда показа уведомления
///   совпадает с срабатыванием `CoreServicesUIAgent` в системном логе;
///   тот же вызов **в главном потоке** агента не поднимает.
/// * **Остальные платформы — в фоновом потоке.** Бэкенд Linux (`dbus`
///   через zbus) может блокироваться, а НФР §8 требует UI-фризы ≤ 16 мс.
///
/// Вызов идёт из обработчика эффектов gpui (`Effect::Notify`), то есть
/// уже из главного потока — синхронный показ на macOS его не блокирует
/// заметно (отправка нотификации асинхронна в системе).
#[cfg(target_os = "macos")]
pub fn show(body: &str) {
    let result = notify_rust::Notification::new()
        .summary("ld2")
        .body(body)
        .show();
    if let Err(e) = result {
        tracing::warn!("OS-уведомление не показано: {e}");
    }
}

/// Показ системного уведомления (ошибка — в лог, не фатально).
/// Linux/Windows — в фоновом потоке, чтобы dbus не держал UI-поток.
#[cfg(not(target_os = "macos"))]
pub fn show(body: &str) {
    let body = body.to_string();
    std::thread::spawn(move || {
        let result = notify_rust::Notification::new()
            .summary("ld2")
            .body(&body)
            .show();
        if let Err(e) = result {
            tracing::warn!("OS-уведомление не показано: {e}");
        }
    });
}
