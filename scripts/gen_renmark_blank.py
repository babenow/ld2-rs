def node_name(pkg_name, roles, i):
    """Имя узла: «<Пакет>: <роль>[, <уточнение>]» — уникально в пакете."""
    n = len(roles)
    role = roles[i % n]
    round_i = i // n
    if round_i == 0:
        return f"{pkg_name}: {role}"
    return f"{pkg_name}: {role}, {QUALS[round_i % len(QUALS)]}"


