def validate(locations, external):
    ids = [l["id"] for l in locations]
    assert len(ids) == len(set(ids)), "дубликаты id"
    assert len(ids) == 1180, f"ожидалось 1180 локаций, получено {len(ids)}"

    known = set(ids) | set(external)
    errors = []

    spawns = [l["id"] for l in locations if l.get("spawn")]
    if len(spawns) != 1:
        errors.append(f"spawn: {len(spawns)} точек ({spawns}), нужно 1")

    names = {}
    for l in locations:
        if not l["text"].strip():
            errors.append(f"{l['id']}: пустой text")
        if not l["exits"]:
            errors.append(f"{l['id']}: нет выходов")
        if l["name"] in names:
            errors.append(
                f"дубль имени «{l['name']}»: {names[l['name']]} и {l['id']}"
            )
        else:
            names[l["name"]] = l["id"]
        seen_dir = set()
        for e in l["exits"]:
            if e["to"] not in known:
                errors.append(f"{l['id']}/{e['id']}: нет цели {e['to']}")
            if e.get("dir"):
                if e["dir"] not in DIRS:
                    errors.append(f"{l['id']}/{e['id']}: неверный dir {e['dir']}")
                if e["dir"] in seen_dir:
                    errors.append(f"{l['id']}: повтор dir {e['dir']}")
                seen_dir.add(e["dir"])
            if not e["label"].strip():
                errors.append(f"{l['id']}/{e['id']}: пустой label")
        ent_ids = [x["id"] for x in l["entities"]]
        if len(ent_ids) != len(set(ent_ids)):
            errors.append(f"{l['id']}: дубликаты сущностей")

    # взаимность обычных переходов
    by_id = {l["id"]: l for l in locations}
    for l in locations:
        for e in l["exits"]:
            tgt = by_id.get(e["to"])
            if tgt is None:
                continue
            if not any(x["to"] == l["id"] for x in tgt["exits"]):
                errors.append(f"невзаимно: {l['id']} → {e['to']} ({e['id']})")

    # связность от спавна (внешние узлы — тупики, через них не идём)
    root = spawns[0] if spawns else ids[0]
    seen, q = {root}, deque([root])
    while q:
        cur = q.popleft()
        for e in by_id[cur]["exits"]:
            nxt = e["to"]
            if nxt in by_id and nxt not in seen:
                seen.add(nxt)
                q.append(nxt)
    if len(seen) != len(ids):
        miss = sorted(set(ids) - seen)[:5]
        errors.append(f"недостижимо из {root}: {len(ids)-len(seen)} шт, напр. {miss}")

    return errors


def main():
    external = []
    if os.path.exists(MAIN):
        with open(MAIN, encoding="utf-8") as f:
            external = [l["id"] for l in json.load(f)["locations"]]

    locations = build()
    errors = validate(locations, external)
    if errors:
        print("ПРОВЕРКА НЕ ПРОЙДЕНА:")
        for e in errors[:40]:
            print("  -", e)
        print(f"всего замечаний: {len(errors)}")
        sys.exit(1)

    with open(OUT, "w", encoding="utf-8") as f:
        json.dump({"locations": locations}, f, ensure_ascii=False, indent=2)
        f.write("\n")

    exits = sum(len(l["exits"]) for l in locations)
    dirs = sum(1 for l in locations for e in l["exits"] if e.get("dir"))
    ents = sum(len(l["entities"]) for l in locations)
    print(f"OK: {len(locations)} локаций, {exits} выходов ({dirs} с dir), {ents} сущностей")
    print(f"файл: {OUT} ({os.path.getsize(OUT)/1024:.0f} КБ)")


if __name__ == "__main__":
    main()
