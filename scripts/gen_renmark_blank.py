def build():
    locations = []
    index = {}  # loc_id -> location dict
    order = []  # (region, pkg, count) в порядке реестра

    for region, region_name, flag, terrain, packages in REGIONS:
        for pkg, pkg_name, count, npc in packages:
            roles = ROLES[terrain]
            details = DETAILS[region]
            conflicts = CONFLICTS[region]
            for i in range(1, count + 1):
                lid = loc_id(region, pkg, i)
                ent = entity_for(region, pkg, pkg_name, npc) if i == 1 else []
                if lid == START:
                    name, text = START_NAME, START_TEXT
                elif i == 1:
                    name, text = pkg_name, node_text(
                        pkg_name, region, roles, details, conflicts, 0
                    )
                else:
                    name = node_name(pkg_name, roles, i - 1)
                    text = node_text(
                        pkg_name, region, roles, details, conflicts, i - 1
                    )
                loc = {
                    "id": lid,
                    "name": name,
                    "spawn": lid == START,
                    "flags": [flag],
                    "text": text,
                    "exits": [],
                    "entities": ent,
                }
                index[lid] = loc
                locations.append(loc)
                order.append((region, pkg, count, terrain))

    used_dirs = {}  # loc_id -> set(занятых dir)
    made = set()  # нормализованные пары, чтобы не дублировать переходы

    def free_dir(loc_id_, hint, taken_by_other):
        """Подходит ли hint для локации: не занят и не зеркалит её же dir."""
        if not hint:
            return None
        if hint in used_dirs.get(loc_id_, set()):
            return None
        if hint in taken_by_other:
            return None
        return hint

    def add(a, b, label, reverse, hint_dir=None, reverse_hint=None):
        """Двусторонний переход; у локации не более одного выхода на dir."""
        if a == b:
            return
        key = (a, b) if a < b else (b, a)
        if key in made:
            return
        made.add(key)
        d1 = free_dir(a, hint_dir, used_dirs.setdefault(b, set()))
        d2 = free_dir(b, reverse_hint, used_dirs.setdefault(a, set()))
        if d1 and d1 == d2:
            d2 = None
        if d1:
            used_dirs[a].add(d1)
        if d2:
            used_dirs[b].add(d2)
        index[a]["exits"].append(
            {
                "id": d1 or f"e_{b.split('_', 2)[-1]}",
                "label": label if not d1 else f"{label} ({RU_DIR[d1]})",
                "to": b,
                **({"dir": d1} if d1 else {}),
            }
        )
        index[b]["exits"].append(
            {
                "id": d2 or f"e_{a.split('_', 2)[-1]}",
                "label": reverse if not d2 else f"{reverse} ({RU_DIR[d2]})",
                "to": a,
                **({"dir": d2} if d2 else {}),
            }
        )

    # 1) кольцо внутри пакета: 01↔02↔…↔NN↔01
    for region, pkg, count, terrain in order:
        for i in range(1, count + 1):
            a = loc_id(region, pkg, i)
            b = loc_id(region, pkg, i % count + 1)
            # dir — только там, где сторона света честна (открытая местность)
            d = DIRS[(i - 1) % 4] if terrain == "wild" else None
            rd = OPP[d] if d else None
            add(
                a,
                b,
                f"пройти к: {index[b]['name']}",
                f"вернуться к: {index[a]['name']}",
                hint_dir=d,
                reverse_hint=rd,
            )

    # 2) каждое пятое место — короткая связь «через пять»
    for region, pkg, count, terrain in order:
        if count < 10:
            continue
        for i in range(5, count + 1, 5):
            a = loc_id(region, pkg, i)
            b = loc_id(region, pkg, i + 5 if i + 5 <= count else i - 5)
            add(
                a,
                b,
                f"срез к: {index[b]['name']}",
                f"срез к: {index[a]['name']}",
            )

    # 3) магистраль региона: NN предыдущего пакета → 01 следующего
    by_region = {}
    for region, pkg, count, terrain in order:
        by_region.setdefault(region, []).append((pkg, count, terrain))
    for region, pkgs in by_region.items():
        for (p1, c1, t1), (p2, c2, t2) in zip(pkgs, pkgs[1:]):
            a = loc_id(region, p1, c1)
            b = loc_id(region, p2, 1)
            add(
                a,
                b,
                f"выход к: {index[b]['name']}",
                f"выход к: {index[a]['name']}",
            )

    # 4) shortcut Вельгарда: стартовая площадь сразу к ремесленному району
    add(
        "l_velgard_sloboda_01",
        "l_velgard_market_01",
        "пройти к: ",
        "пройти к: ",
        hint_dir="north",
        reverse_hint="south",
    )

    # 5) межрегиональные переходы (§4 бланка)
    CROSS = [
        ("l_velgard_sloboda_30", "l_meadows_capital_approach_01", "east", "west"),
        ("l_meadows_royal_road_30", "l_steppe_treaty_stone_01", "east", "west"),
        ("l_meadows_bilberry_yard_24", "l_irven_border_path_01", "south", "north"),
        ("l_meadows_mill_pass_28", "l_teeth_mountain_path_01", "west", "east"),
        ("l_velgard_cathedral_30", "l_under_cathedral_stores_01", None, None),
        ("l_velgard_island_25", "l_under_old_labs_01", None, None),
        ("l_velgard_port_35", "l_under_contraband_ways_01", None, None),
        ("l_velgard_rotten_row_34", "l_under_city_drains_01", None, None),
        ("l_irven_old_irven_38", "l_under_irven_vaults_01", None, None),
        ("l_teeth_deaf_mine_28", "l_under_lower_mines_01", None, None),
        ("l_under_cathedral_stores_26", "l_under_candle_crypt_01", None, None),
    ]
    for a, b, d, rd in CROSS:
        add(
            a,
            b,
            f"выйти к: {index[b]['name']}",
            f"вернуться к: {index[a]['name']}",
            hint_dir=d,
            reverse_hint=rd,
        )

    # 6) стартовый узел: canonical-вид (§6 бланка) + dir у его выходов
    start = index[START]
    start["name"] = START_NAME
    start["text"] = START_TEXT
    # Совместимость с content/locations.json: прежний технический спавн.
    if not any(e["to"] == "l_village" for e in start["exits"]):
        start["exits"].append(
            {"id": "e_village", "label": "дорога к Деревне Избе", "to": "l_village"}
        )
    canon = {
        "l_velgard_market_01": ("north", "арка к Старому рынку"),
        "l_velgard_sloboda_02": ("east", "улица временных жильцов"),
        "l_velgard_sloboda_30": ("south", "дорога к Южным воротам"),
    }
    for e in start["exits"]:
        if e["to"] in canon:
            d, label = canon[e["to"]]
            e["label"] = label
            if d not in used_dirs[START]:
                e["dir"] = d
                used_dirs[START].add(d)
                # обратный dir соседу, если у него он свободен
                back = OPP[d]
                nb = index[e["to"]]
                if back not in used_dirs.get(nb["id"], set()):
                    for be in nb["exits"]:
                        if be["to"] == START and "dir" not in be:
                            be["dir"] = back
                            used_dirs.setdefault(nb["id"], set()).add(back)
                            break

    return locations


